import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { stylesheets } from '../src/config.mjs';
import { root, sourceDir, publicDir, isMain } from './lib/paths.mjs';
import { staticAssets } from './lib/public-files.mjs';

export async function renderStyles() {
  const sections = await Promise.all(stylesheets.map(async name => {
    const css = await readFile(path.join(sourceDir, 'styles', `${name}.css`), 'utf8');
    return `/* src/styles/${name}.css */\n${css.trim()}\n`;
  }));
  return '/* Generated by npm run build. Edit src/styles/ instead. */\n\n' + sections.join('\n');
}

export async function buildAssets() {
  await mkdir(path.join(root, 'assets/css'), { recursive: true });
  await mkdir(path.join(root, 'assets/js'), { recursive: true });
  await writeFile(path.join(root, 'assets/css/styles.css'), await renderStyles());

  for (const script of ['main.js', 'journey.js', 'chatbot.mjs']) {
    const content = await readFile(path.join(sourceDir, 'scripts', script), 'utf8');
    await writeFile(path.join(root, 'assets/js', script), `// Generated by npm run build. Edit src/scripts/${script} instead.\n${content}`);
  }

  for (const asset of staticAssets) {
    await mkdir(path.dirname(path.join(root, asset.output)), { recursive: true });
    await copyFile(path.join(publicDir, asset.source), path.join(root, asset.output));
  }
}

if (isMain(import.meta.url)) await buildAssets();
