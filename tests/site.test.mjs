import assert from 'node:assert/strict';
import { readFile, access, readdir } from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import { root, distDir, sourceDir, publicDir } from '../scripts/lib/paths.mjs';
import { loadContent } from '../scripts/lib/content.mjs';
import { publicFiles, staticAssets } from '../scripts/lib/public-files.mjs';
import { renderPages } from '../scripts/build-pages.mjs';
import { renderStyles } from '../scripts/build-assets.mjs';
import { locales, home, journey, cv } from '../src/config.mjs';

const data = await loadContent();
const renderedPages = await renderPages();
const pages = new Map(await Promise.all([...renderedPages.keys()].map(async filename => [
  filename, await readFile(path.join(root, filename), 'utf8')
])));

test('all languages preserve content, direction, downloads, and standalone journeys', async () => {
  const expectedKeys = Object.keys(data.en.ui).sort();
  for (const lang of locales) {
    const content = data[lang];
    assert.deepEqual(Object.keys(content.ui).sort(), expectedKeys, `${lang}: missing translations`);
    assert.ok(Object.values(content.ui).every(value => typeof value === 'string' && value.trim()));
    assert.equal(content.experience.length, 4);
    assert.equal(content.projects.length, 4);
    assert.equal(content.chapters.length, 6);
    assert.equal(content.education[0].date, '2021–2024');
    for (const filename of [home(lang), journey(lang)]) {
      const html = pages.get(filename);
      assert.ok(html.includes(`<html lang="${lang}" dir="${content.dir}">`));
      assert.ok(!html.includes('<dialog'), 'The journey must be a separate page');
      assert.ok(!html.includes('undefined'), `${filename}: unfilled content`);
      assert.ok(html.includes(`href="${cv(lang)}" download`));
      assert.equal((html.match(/aria-current="page"/g) || []).length, 1);
    }
    assert.ok(pages.get(home(lang)).includes(`href="${journey(lang)}"`));
    assert.equal((pages.get(journey(lang)).match(/class="world-zone"/g) || []).length, 6);
    const payload = /<script type="application\/json" id="journey-data">([\s\S]*?)<\/script>/.exec(pages.get(journey(lang)));
    assert.ok(payload, 'The journey needs its translated chapter data');
    assert.deepEqual(JSON.parse(payload[1]).chapters, content.chapters);
    const pdf = await readFile(path.join(root, cv(lang)));
    assert.equal(pdf.subarray(0, 5).toString(), '%PDF-');
    assert.ok(pdf.length > 20000);
  }
});

test('every relative link and section anchor resolves inside the public site', async () => {
  for (const [filename, html] of pages) {
    for (const [, value] of html.matchAll(/(?:href|src)="([^"]+)"/g)) {
      if (/^(https?:|mailto:)/.test(value)) continue;
      assert.ok(value && value !== '#', `${filename}: placeholder link`);
      const [relative, hash] = value.split('#');
      const target = relative || filename;
      assert.ok(publicFiles.includes(target), `${filename}: non-public link ${value}`);
      await access(path.join(distDir, target));
      if (hash && !/^chapter-[1-6]$/.test(hash)) {
        assert.ok(pages.get(target)?.includes(`id="${hash}"`), `${filename}: broken link ${value}`);
      }
    }
  }
});

test('tracked deployment files are current with their editable sources', async () => {
  for (const [filename, expected] of renderedPages) {
    assert.equal(pages.get(filename), expected, `${filename}: run npm run build`);
  }
  assert.equal(await readFile(path.join(root, 'assets/css/styles.css'), 'utf8'), await renderStyles());
  for (const script of ['main.js', 'journey.js']) {
    const source = await readFile(path.join(sourceDir, 'scripts', script), 'utf8');
    const output = await readFile(path.join(root, 'assets/js', script), 'utf8');
    assert.equal(output, `// Generated by npm run build. Edit src/scripts/${script} instead.\n${source}`);
  }
  for (const asset of staticAssets) {
    assert.deepEqual(await readFile(path.join(publicDir, asset.source)), await readFile(path.join(root, asset.output)));
  }
});

async function listFiles(directory, prefix = '') {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = prefix + entry.name;
    if (entry.isDirectory()) files.push(...await listFiles(path.join(directory, entry.name), relative + '/'));
    else files.push(relative);
  }
  return files.sort();
}

test('dist contains exactly the public files and matches the GitHub Pages root', async () => {
  assert.deepEqual(await listFiles(distDir), [...publicFiles].sort());
  for (const filename of publicFiles) {
    assert.deepEqual(await readFile(path.join(distDir, filename)), await readFile(path.join(root, filename)));
  }
});
